CREATE TABLE users (
  id BIGINT PRIMARY KEY,
  blocked BOOLEAN NOT NULL DEFAULT false,
  created_at BIGINT NOT NULL
);

CREATE TABLE channels (
  id BIGINT PRIMARY KEY,
  owner_id BIGINT NOT NULL REFERENCES users(id),
  title TEXT NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT false,
  available BOOLEAN NOT NULL DEFAULT true,
  daily_limit INTEGER NOT NULL CHECK (daily_limit BETWEEN 1 AND 5),
  topics JSONB NOT NULL CHECK (jsonb_typeof(topics) = 'array'),
  revision INTEGER NOT NULL DEFAULT 0,
  blocked_until BIGINT NOT NULL DEFAULT 0,
  last_attempt_at BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX channels_owner ON channels(owner_id);
CREATE INDEX channels_due ON channels(daily_limit, last_attempt_at) WHERE enabled AND available;

CREATE TABLE news (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  url TEXT NOT NULL,
  title TEXT NOT NULL,
  excerpt TEXT NOT NULL,
  source TEXT NOT NULL,
  published_at BIGINT NOT NULL,
  uz_title TEXT,
  uz_summary TEXT,
  attempts INTEGER NOT NULL DEFAULT 0,
  retry_at BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX news_recent ON news(published_at DESC);

CREATE TABLE news_keys (
  key TEXT PRIMARY KEY,
  news_id BIGINT NOT NULL REFERENCES news(id)
);

CREATE TABLE publications (
  channel_id BIGINT NOT NULL REFERENCES channels(id),
  news_id BIGINT NOT NULL REFERENCES news(id),
  day TEXT NOT NULL,
  reserved_at BIGINT NOT NULL,
  state TEXT NOT NULL CHECK (state IN ('reserved', 'sent', 'uncertain')),
  message_id BIGINT,
  digest_id BIGINT,
  PRIMARY KEY (channel_id, news_id)
);
CREATE INDEX publications_daily ON publications(channel_id, day);
CREATE INDEX publications_digest ON publications(channel_id, COALESCE(digest_id, news_id));

CREATE TABLE bot_state (
  key TEXT PRIMARY KEY,
  value JSONB NOT NULL
);
